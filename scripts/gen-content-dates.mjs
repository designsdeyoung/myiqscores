// Generates src/generated/contentDates.ts from git history so every page can
// show a truthful "Last updated" date and emit a real dateModified in schema.
// Runs at the start of every build (see package.json build script); dates
// refresh automatically whenever a data file or page component changes.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

function gitDate(...files) {
  let max = "";
  for (const file of files) {
    try {
      const d = execSync(`git log -1 --format=%cs -- "${file}"`, { cwd: repoRoot, encoding: "utf-8" }).trim();
      if (d > max) max = d;
    } catch {
      // ignore
    }
  }
  return max || new Date().toISOString().slice(0, 10);
}

// Route-family dates from the data files that power each template.
const familyDates = [
  { prefix: "/is-", date: gitDate("src/data/iqScoreData.ts", "src/data/iqExtendedData.ts", "src/data/iqExtendedDataMid.ts", "src/data/iqExtendedDataHigh.ts") },
  { prefix: "/famous-iq/", date: gitDate("src/data/famousIQData.ts") },
  { prefix: "/average-iq/", date: gitDate("src/data/countryIQData.ts", "src/data/countryExtendedData.ts") },
  { prefix: "/average-iq-by-state/", date: gitDate("src/data/stateIQData.ts") },
  { prefix: "/iq-by-city/", date: gitDate("src/data/cityIQData.ts") },
  { prefix: "/iq-needed-for/", date: gitDate("src/data/careerIQData.ts", "src/data/careerExtendedData.ts") },
  { prefix: "/iq-by-major/", date: gitDate("src/data/majorIQData.ts") },
  { prefix: "/iq-by-age/", date: gitDate("src/data/ageIQData.ts") },
  { prefix: "/iq-and/", date: gitDate("src/data/conditionIQData.ts") },
  { prefix: "/iq-myths/", date: gitDate("src/data/iqMythData.ts") },
  { prefix: "/iq-compare/", date: gitDate("src/data/iqCompareData.ts") },
];

// Per-route dates for static pages, from each page component's git history
// (route -> component mapping parsed from App.tsx).
const appSrc = fs.readFileSync(path.resolve(repoRoot, "src/App.tsx"), "utf-8");
const imports = new Map();
for (const m of appSrc.matchAll(/import\s+(\w+)\s+from\s+"\.\/((?:pages|components)\/[^"]+)"/g)) {
  imports.set(m[1], `src/${m[2]}`);
}
const routeDates = {};
for (const m of appSrc.matchAll(/<Route\s+path="(\/[^"]*)"\s+element={<(\w+)\s*\/>}/g)) {
  const file = imports.get(m[2]);
  if (file && !m[1].includes("*")) routeDates[m[1]] = gitDate(file);
}

const out = `// AUTO-GENERATED by scripts/gen-content-dates.mjs. Do not edit by hand.
// Last-updated dates derived from git history: data files for programmatic
// page families, page components for static routes.

export const familyDates: { prefix: string; date: string }[] = ${JSON.stringify(familyDates, null, 2)};

export const routeDates: Record<string, string> = ${JSON.stringify(routeDates, null, 2)};

export function contentDateFor(pathname: string): string | null {
  if (routeDates[pathname]) return routeDates[pathname];
  for (const f of familyDates) {
    if (pathname.startsWith(f.prefix)) return f.date;
  }
  return null;
}

const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

export function formatContentDate(iso: string): string {
  const [y, m, d] = iso.split("-").map(Number);
  return \`\${MONTHS[(m ?? 1) - 1]} \${d}, \${y}\`;
}
`;

fs.mkdirSync(path.resolve(repoRoot, "src/generated"), { recursive: true });
fs.writeFileSync(path.resolve(repoRoot, "src/generated/contentDates.ts"), out);
console.log(`contentDates.ts: ${familyDates.length} families, ${Object.keys(routeDates).length} static routes`);
